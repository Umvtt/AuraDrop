function paint(id, extra = {}) {
  const p = PAINTS.find((x) => x.id === id) ?? PAINTS[0];
  return { base: p.base, camo: p.camo, c1: p.colors[0], c2: p.colors[1], c3: p.colors[2], gloss: p.gloss ? 0.6 : p.metal ? 0.4 : 0.1, ...extra };
}

